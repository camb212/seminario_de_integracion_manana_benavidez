import math

distancia = 225

print("Raíz cuadrada de la distancia:")
print(math.sqrt(distancia))

dias_estimados = 3.2

print("Redondear días hacia arriba:")
print(math.ceil(dias_estimados))

print("Redondear días hacia abajo:")
print(math.floor(dias_estimados))

costo_km = 3.555552

print("Costo por km redondeado a 2 decimales:")
print(round(costo_km, 2))